import os
import re
import importlib
import subprocess
from typing import List, Dict


def extract_functions_from_code() -> List[Dict]:
    """Extract all functions from code_extracted.txt"""
    with open("final_res/code_extracted_eoh_opt_re.txt", "r") as f:
        content = f.read()

    # Split different code blocks using regex
    code_blocks = re.split(r'=+\n\n', content)

    functions = []
    for block in code_blocks:
        if not block.strip():
            continue

        # Extract source information
        source_match = re.search(r'# Source: (.+?)\n', block)
        source = source_match.group(1) if source_match else "unknown"

        # Extract objective value
        objective_match = re.search(r'# Objective: (.+?)\n', block)
        objective = objective_match.group(1) if objective_match else "unknown"

        # Extract function code
        function_match = re.search(r'(def \w+\(.*?\).*?\n(?: {4}.*?\n)*)', block, re.DOTALL)
        if function_match:
            functions.append({
                'source': source,
                'objective': objective,
                'code': function_match.group(1).strip()
            })

    return functions


def evaluate_functions(functions: List[Dict]):
    """Evaluate all functions and record results"""
    results = []

    for i, func in enumerate(functions, 1):
        print(f"\nEvaluating function {i}/{len(functions)} from {func['source']}")

        # 1. Write current function to heuristic.py
        with open("heuristic.py", "w") as f:
            f.write("# Auto-generated by autoEval.py\n")
            f.write("import numpy as np\n")
            f.write(func['code'] + "\n")

        # 2. Run runEval.py to evaluate the function
        try:
            result = subprocess.run(
                ["python", "runEval.py"],
                capture_output=True,
                text=True,
                check=True
            )
            output = result.stdout.strip()
            print(f"Evaluation output:\n{output}")
        except subprocess.CalledProcessError as e:
            output = f"Error: {e.stderr.strip()}"
            print(f"Evaluation failed:\n{output}")

        # 3. Record results
        results.append({
            'source': func['source'],
            'training_objective': func['objective'],
            'evaluation_output': output
        })

    # 4. Save all evaluation results
    with open("eval_results.txt", "w") as f:
        for res in results:
            f.write(f"Source: {res['source']}\n")
            f.write(f"Training Objective: {res['training_objective']}\n")
            f.write("Evaluation Output:\n")
            f.write(res['evaluation_output'] + "\n")
            f.write("=" * 80 + "\n\n")

    print("\nAll evaluations completed. Results saved to eval_results.txt")


def main():
    # Check if required files exist
    required_files = ["code_extracted.txt", "runEval.py"]
    for f in required_files:
        if not os.path.exists(f):
            raise FileNotFoundError(f"Required file not found: {f}")

    # Extract and evaluate functions
    functions = extract_functions_from_code()
    if not functions:
        print("No functions found in code_extracted.txt")
        return

    print(f"Found {len(functions)} functions to evaluate")
    evaluate_functions(functions)


if __name__ == "__main__":
    main()