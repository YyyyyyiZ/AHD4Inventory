    selected_m = 7 if abs(m - 7) <= abs(m - 8) else 8
    selected_cv = 1.5 if abs(cv - 1.5) <= abs(cv - 2.0) else 2.0
    selected_f = 0.0 if abs(f) <= abs(f - 0.5) else 0.5
    theta = np.asarray(
        table[(selected_m, selected_cv, selected_f)],
        dtype=np.float64,
    )

    def policy(age, pipeline):
        target_gap = theta[0]

        for k in range(len(pipeline)):
            target_gap -= theta[1] * pipeline[k]

        usable_weights = min(len(age), len(theta) - 3)
        for i in range(usable_weights):
            target_gap -= theta[3 + i] * age[i]

        if target_gap <= 0.0:
            return 0.0
        if target_gap >= theta[2]:
            return theta[2]
        return target_gap

    return policy
